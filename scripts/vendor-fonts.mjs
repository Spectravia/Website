/**
 * Copies the site fonts into the repo so every build works offline
 * (the static build must not depend on downloading fonts at build time).
 *
 *   npm run fonts
 *
 * Fetches the Fontsource packages from npm, copies the needed .woff2 files to
 * public/fonts/ and writes app/assets/css/fonts.css (@font-face rules).
 * Commit both. Change the families/weights/subsets below, then re-run.
 */
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const weights = [300, 400, 500, 600, 700]
const fonts = [
  { pkg: '@fontsource/sora', version: '5.3.0', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource/ibm-plex-sans', version: '5.3.0', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource/ibm-plex-sans-arabic', version: '5.3.0', subsets: ['arabic', 'latin'] },
]

const outDir = join(root, 'public', 'fonts')
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const tmp = mkdtempSync(join(tmpdir(), 'fonts-'))
let css = '/* Generated by scripts/vendor-fonts.mjs - do not edit by hand. Fonts: SIL Open Font License. */\n'

for (const { pkg, version, subsets } of fonts) {
  const tgz = execFileSync('npm', ['pack', `${pkg}@${version}`, '--silent', '--pack-destination', tmp], { encoding: 'utf8' }).trim()
  const dir = join(tmp, tgz.replace(/\.tgz$/, ''))
  mkdirSync(dir)
  execFileSync('tar', ['xzf', join(tmp, tgz), '-C', dir])
  const pkgDir = join(dir, 'package')

  for (const weight of weights) {
    // <weight>.css holds one @font-face per subset, each with its unicode-range
    const faces = readFileSync(join(pkgDir, `${weight}.css`), 'utf8').split(/(?=\/\* )/)
    for (const subset of subsets) {
      const face = faces.find(f => f.startsWith(`/* ${pkg.split('/')[1]}-${subset}-${weight}-normal */`))
      if (!face) throw new Error(`${pkg} has no ${subset} ${weight} face`)
      const file = face.match(/files\/([\w-]+\.woff2)/)[1]
      copyFileSync(join(pkgDir, 'files', file), join(outDir, file))
      css += '\n' + face
        .replace(/src:[^;]+;/, `src: url(/fonts/${file}) format('woff2');`)
        .trim() + '\n'
    }
  }
  copyFileSync(join(pkgDir, 'LICENSE'), join(outDir, `LICENSE-${pkg.split('/')[1]}.txt`))
}

writeFileSync(join(root, 'app', 'assets', 'css', 'fonts.css'), css)
rmSync(tmp, { recursive: true, force: true })
console.log(`Fonts written to public/fonts (${readdirSync(outDir).length} files) and app/assets/css/fonts.css`)
